import { Candidate } from '../types';

export function downloadCandidateJSON(candidate: Candidate) {
  const cleanName = `${candidate.firstName}_${candidate.lastName}`.toLowerCase().replace(/[^a-z0-9]/g, '_');
  const payload = JSON.stringify(candidate, null, 2);
  const blob = new Blob([payload], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${cleanName}_talent_profile.json`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function downloadCandidateReport(candidate: Candidate) {
  const cleanName = `${candidate.firstName}_${candidate.lastName}`.toLowerCase().replace(/[^a-z0-9]/g, '_');
  const certs = (candidate.certifications && candidate.certifications.length > 0)
    ? candidate.certifications
    : ['BLS', 'ACLS', 'State Clinical License'];

  const report = `=====================================================
TALENTFLOW ATS - CLINICAL CANDIDATE DOSSIER
=====================================================
Name:         ${candidate.firstName} ${candidate.lastName}
Specialty:    ${candidate.specialty}
Position:     ${candidate.position}
Tenure:       ${candidate.experience} Years Clinical Experience
Location:     ${candidate.currentLocation}
Contact:      ${candidate.email} | ${candidate.phone}
Status:       ${candidate.status.toUpperCase()}
Verification: ${candidate.verifiedByRecruiter ? 'Verified by Recruiter' : 'Pending Verification'}
Accuracy:     ${candidate.confidenceScore || 95}% Extraction Confidence
Source File:  ${candidate.resumeFilename} (Ingested ${candidate.uploadedAt})

CERTIFICATIONS & CREDENTIALS:
${certs.map(c => `• ${c}`).join('\n')}

PROFESSIONAL SUMMARY:
${candidate.professionalSummary}

CLINICAL EXPERIENCE TIMELINE:
${candidate.experienceTimeline.map((exp, i) => `
[${i + 1}] ${exp.position} - ${exp.facility} (${exp.location})
    Tenure: ${exp.startDate} - ${exp.endDate}
    Scope:  ${exp.description}
`).join('')}

PREVIOUS TRAVEL / WORK ASSIGNMENTS:
${candidate.previousTravelLocations.join(', ')}

=====================================================
Generated by TalentFlow ATS Clinical Matching System
`;

  const blob = new Blob([report], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${cleanName}_clinical_dossier.txt`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
